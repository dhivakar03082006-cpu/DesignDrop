let memoryStore: StoreData | null = null;

export function getStore(): StoreData {
  if (memoryStore) return memoryStore;
  try {
    if (!fs.existsSync(DATA_DIR)) {
      fs.mkdirSync(DATA_DIR, { recursive: true });
    }
    if (fs.existsSync(DATA_FILE)) {
      const raw = fs.readFileSync(DATA_FILE, 'utf-8');
      const parsed = JSON.parse(raw) as StoreData;
      // Merge in any newly added seed products and refreshed category visuals
      const existingIds = new Set(parsed.products.map((p) => p.id));
      let updated = false;
      for (const sp of SEED_PRODUCTS) {
        if (!existingIds.has(sp.id)) {
          parsed.products.push(sp);
          updated = true;
        }
      }
      for (const seedCat of SEED_DATA.categories) {
        const existingCat = parsed.categories.find((c) => c.id === seedCat.id);
        if (!existingCat) {
          parsed.categories.push(seedCat);
          updated = true;
        } else if (existingCat.imageUrl !== seedCat.imageUrl) {
          existingCat.imageUrl = seedCat.imageUrl;
          updated = true;
        }
      }
      if (updated) saveStore(parsed);
      memoryStore = parsed;
      return memoryStore;
    }
  } catch {
    // Fallback to seed data in memory
  }
  memoryStore = structuredClone(SEED_DATA);
  saveStore(memoryStore);
  return memoryStore;
}

export function saveStore(data: StoreData): void {
  memoryStore = data;
  try {
    if (!fs.existsSync(DATA_DIR)) {
      fs.mkdirSync(DATA_DIR, { recursive: true });
    }
    fs.writeFileSync(DATA_FILE, JSON.stringify(data, null, 2), 'utf-8');
  } catch {
    // Ignore filesystem errors in read-only runtimes
  }
}

